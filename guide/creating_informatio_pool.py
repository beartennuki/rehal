def generate_subtopics(topic: str, min_subtopics: int = 4, max_subtopics: int = 10) -> List[str]:
    prompt = f"""
Break this topic into {min_subtopics} to {max_subtopics} important subtopics.

Topic:
{topic}

Rules:
- Subtopics must be useful for a canonical educational document.
- Avoid overlap.
- Keep subtopics short.
- Return JSON array only.
"""

    result = ask_openai_json(prompt)

    if not isinstance(result, list):
        raise ValueError("Subtopics must be a list.")

    return [str(x).strip() for x in result if str(x).strip()][:max_subtopics]


# ---------------------------------------------------------
# Tavily search with source filtering
# ---------------------------------------------------------

def tavily_search_quality_sources(
    topic: str,
    subtopic: str,
    max_results: int = 10,
    max_tier: int = 3
) -> List[Dict[str, Any]]:

    query = f"{topic} {subtopic} explanation research technical source"

    response = tavily_client.search(
        query=query,
        search_depth="advanced",
        max_results=max_results,
        include_answer=False,
        include_raw_content=True
    )

    sources = []

    for item in response.get("results", []):
        url = item.get("url")
        raw_content = item.get("raw_content") or item.get("content") or ""

        if not url or not raw_content:
            continue

        tier = source_quality_tier(url)

        if tier > max_tier:
            continue

        sources.append({
            "title": item.get("title"),
            "url": url,
            "domain": get_domain(url),
            "tavily_score": item.get("score"),
            "source_quality_tier": tier,
            "source_weight": source_weight(tier),
            "raw_content": raw_content[:12000],
        })

    return dedupe_sources(sources)


# ---------------------------------------------------------
# Fallback search if source quality is poor
# ---------------------------------------------------------

def search_with_fallback(
    topic: str,
    subtopic: str,
    min_sources: int = 3
) -> List[Dict[str, Any]]:

    sources = tavily_search_quality_sources(
        topic=topic,
        subtopic=subtopic,
        max_results=10,
        max_tier=3
    )

    if len(sources) >= min_sources:
        return sources

    refined_queries = [
        f"{topic} {subtopic} site:arxiv.org OR site:ieee.org OR site:acm.org",
        f"{topic} {subtopic} research paper",
        f"{topic} {subtopic} university explanation",
    ]

    for query in refined_queries:
        response = tavily_client.search(
            query=query,
            search_depth="advanced",
            max_results=10,
            include_answer=False,
            include_raw_content=True
        )

        for item in response.get("results", []):
            url = item.get("url")
            raw_content = item.get("raw_content") or item.get("content") or ""

            if not url or not raw_content:
                continue

            tier = source_quality_tier(url)

            if tier <= 3:
                sources.append({
                    "title": item.get("title"),
                    "url": url,
                    "domain": get_domain(url),
                    "tavily_score": item.get("score"),
                    "source_quality_tier": tier,
                    "source_weight": source_weight(tier),
                    "raw_content": raw_content[:12000],
                })

        sources = dedupe_sources(sources)

        if len(sources) >= min_sources:
            break

    return sources


