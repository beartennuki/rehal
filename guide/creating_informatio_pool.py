def content_hash(text: str, length: int = 2000) -> str:
    clean = re.sub(r"\s+", " ", text or "").strip().lower()
    clean = clean[:length]
    return hashlib.sha256(clean.encode("utf-8")).hexdigest()


def dedupe_sources(sources: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Deduplicate by:
    - same domain
    - near-identical beginning content hash

    This prevents duplicated SlideShare / mirrored pages
    from being counted as independent corroboration.
    """

    seen_domains = set()
    seen_hashes = set()
    deduped = []

    for source in sources:
        url = source.get("url", "")
        raw_content = source.get("raw_content", "")

        domain = get_domain(url)
        h = content_hash(raw_content)

        if domain in seen_domains:
            continue

        if h in seen_hashes:
            continue

        seen_domains.add(domain)
        seen_hashes.add(h)

        deduped.append(source)

    return deduped


