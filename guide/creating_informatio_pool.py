from typing import Dict, Any, List


def embed_canonical_claims(
    verified_claims: Dict[str, Any],
    model: str = "text-embedding-3-small"
) -> Dict[str, Any]:
    """
    Convert each canonical_claim into an embedding vector.

    Input:
        verified_claims = {
            "verified_claims": [
                {
                    "canonical_claim": "...",
                    "trust_label": "high",
                    "weighted_support_score": 5.2,
                    ...
                }
            ]
        }

    Output:
        Same structure, but each claim now has an "embedding" field.
    """

    embedded_claims = []

    for item in verified_claims.get("verified_claims", []):
        claim_text = item.get("canonical_claim", "")

        if not claim_text:
            continue

        response = openai_client.embeddings.create(
            model=model,
            input=claim_text
        )

        vector = response.data[0].embedding

        embedded_item = {
            **item,
            "embedding_model": model,
            "embedding": vector
        }

        embedded_claims.append(embedded_item)

    return {
        "verified_claims": embedded_claims
    }

