def ask_openai_json(
    prompt: str,
    model: str = "gpt-5.4-mini",
    temperature: float = 0.2,
    max_retries: int = 3
) -> Any:

    last_error = None
    last_content = None

    for attempt in range(1, max_retries + 1):
        response = openai_client.chat.completions.create(
            model=model,
            temperature=temperature,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a careful research assistant. "
                        "Return valid JSON only. No markdown. "
                        "Do not include explanations outside JSON."
                    )
                },
                {"role": "user", "content": prompt}
            ]
        )

        content = response.choices[0].message.content
        last_content = content

        try:
            return json.loads(content)

        except json.JSONDecodeError as e:
            last_error = e
            print(f"Attempt {attempt} failed: Invalid JSON")

            # Try extracting JSON from messy output
            try:
                match = re.search(r"\{.*\}|\[.*\]", content, re.DOTALL)
                if match:
                    return json.loads(match.group(0))
            except json.JSONDecodeError as e2:
                last_error = e2

    raise ValueError(
        f"OpenAI failed to return valid JSON after {max_retries} attempts.\n\n"
        f"Last JSON error: {last_error}\n\n"
        f"Last content:\n{last_content}"
    )

