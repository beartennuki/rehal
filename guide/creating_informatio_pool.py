def build_canonical_topic_json_v2(
    topic: str,
    output_path: str = "canonical_document_v2.json",
    min_subtopics: int = 4,
    max_subtopics: int = 10,
    min_sources_per_subtopic: int = 3
) -> Dict[str, Any]:

    subtopics = generate_subtopics(
        topic=topic,
        min_subtopics=min_subtopics,
        max_subtopics=max_subtopics
    )

    all_subtopic_outputs = []
    all_claims = []

    for subtopic in subtopics:
        print(f"Processing subtopic: {subtopic}")

        sources = search_with_fallback(
            topic=topic,
            subtopic=subtopic,
            min_sources=min_sources_per_subtopic
        )

        if not sources:
            all_subtopic_outputs.append({
                "subtopic": subtopic,
                "warning": "No quality sources found.",
                "claims": []
            })
            continue

        extracted = extract_claims_from_sources(
            topic=topic,
            subtopic=subtopic,
            sources=sources
        )

        extracted["sources_used"] = [
            {
                "source_id": source.get("source_id"),
                "title": source.get("title"),
                "url": source.get("url"),
                "domain": source.get("domain"),
                "source_quality_tier": source.get("source_quality_tier"),
                "source_weight": source.get("source_weight"),
            }
            for source in sources
        ]

        all_subtopic_outputs.append(extracted)

        for claim in extracted.get("claims", []):
            claim["subtopic"] = subtopic
            all_claims.append(claim)

    clustered = cluster_claims_strict(all_claims)

    verified = verify_clusters_weighted(clustered)

    embedded_verified = embed_canonical_claims(verified)

    document = write_canonical_document(
        topic=topic,
        subtopics=subtopics,
        verified_claims=verified,
        model="gpt-4.1"
    )

    document["metadata"] = {
        "created_at": datetime.utcnow().isoformat(),
        "topic": topic,
        "subtopics": subtopics,
        "pipeline_version": "v2_source_quality_weighted_trust",
        "notes": [
            "Sources filtered by quality tier before extraction.",
            "Duplicate domains and near-identical content removed before trust scoring.",
            "Trust labels use weighted source quality, not raw source count.",
            "Low-trust claims are forbidden from canonical prose."
        ]
    }

    document["intermediate"] = {
    "subtopic_extractions": all_subtopic_outputs,
    "clustered_claims": clustered,
    "verified_claims": verified,
    "embedded_verified_claims": embedded_verified
}
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(document, f, indent=2, ensure_ascii=False)

    return document

