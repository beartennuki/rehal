def get_domain(url: str) -> str:
    return urlparse(url).netloc.lower().replace("www.", "")


def source_quality_tier(url: str) -> int:
    """
    Lower is better.

    1 = peer-reviewed / preprint / technical academic
    2 = institutional
    3 = strong technical company source
    4 = general source
    5 = weak / commentary / marketing
    """

    domain = get_domain(url)

    tier_1 = [
        "arxiv.org",
        "springer.com",
        "nature.com",
        "science.org",
        "acm.org",
        "ieee.org",
        "sciencedirect.com",
        "iopscience.iop.org",
        "jmlr.org",
    ]

    tier_2 = [
        ".edu",
        ".gov",
        "who.int",
        "oecd.org",
        "unesco.org",
    ]

    tier_3 = [
        "nvidia.com",
        "developer.nvidia.com",
        "research.google",
        "ai.googleblog.com",
        "ai.meta.com",
        "openai.com",
        "microsoft.com/en-us/research",
        "deepmind.google",
    ]

    tier_5 = [
        "slideshare.net",
        "scribd.com",
        "linkedin.com",
        "medium.com",
        "prnewswire.com",
        "businesswire.com",
        "substack.com",
    ]

    if any(d in domain for d in tier_1):
        return 1

    if any(d in domain for d in tier_2):
        return 2

    if any(d in domain for d in tier_3):
        return 3

    if any(d in domain for d in tier_5):
        return 5

    return 4


def source_weight(tier: int) -> float:
    weights = {
        1: 3.0,
        2: 2.0,
        3: 1.2,
        4: 0.7,
        5: 0.2,
    }
    return weights.get(tier, 0.5)


